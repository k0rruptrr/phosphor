namespace Phosphor.Core;

/// <summary>Погодные коды WMO (как в Open-Meteo) → короткие русские слова капсом и значок.</summary>
public static class Wmo
{
    public static string Ru(int code) => code switch
    {
        0 => "ЯСНО",
        1 => "МАЛООБЛАЧНО",
        2 => "ОБЛАЧНО",
        3 => "ПАСМУРНО",
        45 or 48 => "ТУМАН",
        51 or 53 or 55 => "МОРОСЬ",
        56 or 57 => "ЛЕДЯНАЯ МОРОСЬ",
        61 or 63 => "ДОЖДЬ",
        65 => "СИЛЬНЫЙ ДОЖДЬ",
        66 or 67 => "ЛЕДЯНОЙ ДОЖДЬ",
        71 or 73 => "СНЕГ",
        75 => "СНЕГОПАД",
        77 => "СНЕЖНАЯ КРУПА",
        80 or 81 => "ЛИВЕНЬ",
        82 => "СИЛЬНЫЙ ЛИВЕНЬ",
        85 or 86 => "СНЕЖНЫЙ ЗАРЯД",
        95 => "ГРОЗА",
        96 or 97 or 99 => "ГРОЗА С ГРАДОМ",
        _ => "НЕТ ДАННЫХ",
    };

    /// <summary>Один символ из GlyphSet для табло: ☼ ясно, ○ облачно, ≈ туман, ∙ морось, ▼ дождь, * снег, ♦ гроза.</summary>
    public static char Icon(int code) => code switch
    {
        0 or 1 => '☼',
        2 or 3 => '○',
        45 or 48 => '≈',
        >= 51 and <= 57 => '∙',
        >= 61 and <= 67 or >= 80 and <= 82 => '▼',
        >= 71 and <= 77 or 85 or 86 => '*',
        >= 95 => '♦',
        _ => '?',
    };
}
