    private static readonly Dictionary<char, int[]> Cache = Build();

    /// <summary>Биты секстантов 3×3 клеток: индекс cy*3+cx, бит dy*2+dx внутри клетки. Пробел и неизвестные — нули.</summary>
    public static int[] Bits(char c) => Cache.TryGetValue(c, out var b) ? b : EmptyBits;

    /// <summary>Есть ли глиф (пробел в таблицу не входит: он рисуется пустыми клетками).</summary>
    public static bool Has(char c) => Cache.ContainsKey(c);

    private static Dictionary<char, int[]> Build()
    {
        var r = new Dictionary<char, int[]>();
        foreach (var (ch, rows) in Src)
        {
            var bits = new int[CellsW * CellsH];
            for (int sy = 0; sy < CellsH * 3; sy++)
                for (int sx = 0; sx < CellsW * 2; sx++)
                {
                    bool on = sy < rows.Length && sx < rows[sy].Length && rows[sy][sx] == '#';
                    if (!on) continue;
                    int cx = sx / 2, dx = sx % 2, cy = sy / 3, dy = sy % 3;
                    bits[cy * CellsW + cx] |= 1 << (dy * 2 + dx);
                }
            r[ch] = bits;
        }
        return r;
    }
