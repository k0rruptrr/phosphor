/// <summary>
/// Пиксельный шрифт 5×7 для крупного OSD. Символ занимает 3×3 клетки; клетка — 2×3 подпикселя (секстант),
/// поэтому 5 колонок и 7 строк букв укладываются в 6×9 подпикселей, последние колонка и 2 строки пустые.
/// Таблица — строки сверху вниз, '#' — подпиксель горит. Полный латинский алфавит A–Z, цифры и знаки для OSD видика и названий спутников.
